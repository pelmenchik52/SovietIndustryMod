package com.sovietindustry.api;

/**
 * Опора, де на кожну точку кріплення йде не один дріт, а пучок: кілька гірлянд (подвійна гірлянда),
 * а на кожній гірлянді кілька дротів (розщеплена фаза). LepWireRenderer розкладає це в геометрію.
 *
 * Зміщення вздовж осі пучка для гірлянди s і дроту w:
 *   (s - (S-1)/2) * stringSpacing + (w - (W-1)/2) * wireSpacing
 */
public interface IBundledPylon {

    /** Скільки гірлянд висить на одній фазі (2 = подвійна гірлянда). */
    int getStringsPerMount();

    /** Відстань між гірляндами однієї фази в блоках. */
    double getStringSpacing();

    /** Скільки дротів іде з кожної гірлянди. */
    int getWiresPerString();

    /** Відстань між дротами однієї гірлянди в блоках. */
    double getWireSpacing();

    /**
     * Одиничний горизонтальний вектор осі пучка {x, y, z} для дроту, що йде в бік (spanX, spanZ).
     * Для підвісної опори це вісь траверси, для анкерної перпендикуляр до дроту.
     */
    double[] getBundleAxis(double spanX, double spanZ);
}
