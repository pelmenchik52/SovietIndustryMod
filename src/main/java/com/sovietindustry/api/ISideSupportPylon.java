package com.sovietindustry.api;

import net.minecraft.util.Vec3;

/**
 * Анкерна опора, де шлейф фази проходить через горизонтальну допоміжну гірлянду, закріплену на сусідній вежі:
 * вхід (натяжна гірлянда) -> кінець допоміжної гірлянди -> вихід (друга натяжна гірлянда).
 */
public interface ISideSupportPylon {

    /** {точка кріплення на сусідній вежі, вільний кінець гірлянди} відносно кута блока або null, якщо для цієї точки опори нема. */
    Vec3[] getSideSupport(int mount);
}
