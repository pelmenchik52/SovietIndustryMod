package com.sovietindustry.api;

/**
 * Опора, де натяжна гірлянда починається не прямо в точці кріплення, а на деякій відстані від каркаса:
 * від точки кріплення до кореня гірлянди йде коротка сталева підвіска (як на анкерній опорі на фото).
 * Це не дає гірлянді проходити крізь ґратчасті елементи опори.
 */
public interface IStandoffPylon {

    /**
     * Відстань у блоках від точки кріплення до кореня гірлянди вздовж горизонтальної проєкції напрямку дроту.
     *
     * @param mount індекс точки кріплення (як у getMountPos)
     * @param dirX  горизонтальна складова одиничного напрямку гірлянди у СВІТОВИХ осях
     * @param dirZ  те саме по Z
     */
    double getStringStandoff(int mount, double dirX, double dirZ);
}
