package com.sovietindustry.api;

import net.minecraft.util.Vec3;

/**
 * Анкерна опора, де шлейф фази без допоміжної гірлянди на сусідній вежі просто провисає збоку
 * (вільна дуга). Напрям залежить від того, з якого боку кут між натяжними гірляндами менший за 180 градусів.
 */
public interface IFreeLoopPylon {

    /** Вершина вільної дуги шлейфу фази mount (світові координати відносно кута блока) або null, якщо шлейф тримає сусід. */
    Vec3 getFreeLoopApex(int mount);
}
