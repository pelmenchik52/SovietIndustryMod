package com.sovietindustry.api;

import net.minecraft.util.Vec3;

/**
 * Анкерна опора, де проводи однієї фази проходять через додаткові (верхні) гірлянди: дріт від нижньої
 * натяжної гірлянди йде вгору до верхньої гірлянди і з неї назад донизу до протилежної сторони.
 * Верхні гірлянди й шлейф малює LepWireRenderer лише тоді, коли до цієї фази підключено дріт.
 */
public interface IJumperPylon {

    /** Індекс точки кріплення (getMountPos), чий дріт іде в обхід через верхні гірлянди. */
    int getJumperMount();

    /** Верхні гірлянди: для кожної {верх, низ} відносно кута блока (у світових осях, уже з поворотом). */
    Vec3[][] getJumperStrings();

    /** Одиничний горизонтальний вектор, уздовж якого розсовуються дроти на кінці верхньої гірлянди. */
    double[] getJumperAxis();
}
