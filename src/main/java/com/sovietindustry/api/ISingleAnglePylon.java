package com.sovietindustry.api;

/**
 * Окрема анкерно-кутова щогла на одну фазу (750 кВ і 500 кВ). Потрібна рендеру дротів, щоб однаково
 * малювати шлейф такої щогли незалежно від класу напруги.
 */
public interface ISingleAnglePylon {

    /** -1 ліва, 0 середня, +1 права/бічна. */
    int getVariant();

    /** Бік упору допоміжної гірлянди вздовж локальної осі X: +1 або -1. */
    double getSupportDir();
}
